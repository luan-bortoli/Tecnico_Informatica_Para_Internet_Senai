// // IGUAL (==): Verificar se o valor é igual
console.log('10' == 10); // TRUE
console.log(10 == 10); // TRUE

// // ESTRITAMENTE IGUAL (===): Verificar se o tipo e o valor são iguais
console.log('10' === 10); // FALSE
console.log(10 === 10); // TRUE

// // Diferente (!=) Verificar se o valor é diferente
console.log('11' != 10); // TRUE
console.log(11 != 10); // TRUE

// ESTRITAMENTE DIFERENTE (!==): Verificar se o tipo e o valor são diferentes
console.log('11' !== 10); // TRUE
console.log(11 !== 10); // TRUE

//Maior
console.log(19 > 18); //TRUE
console.log(14 > 300); //False

//Maior ou Igual que
console.log(19 >= 19); //TRUE
console.log(20 >= 18); //TRUE

//Menor 
console.log(70 < 100); //TRUE
console.log(32 < 10); // FALSE

//Menor ou Igual Que
console.log(11 <= 48); //TRUE
console.log(2 <= 4); //TRUE

//Exemplos com variáveis
let numeroA = 1;
let numeroB = 10;

console.log(numeroA === numeroB);
console.log(numeroA !== numeroB);
console.log(numeroA > numeroB);
console.log(numeroA >= numeroB);
console.log(numeroA < numeroB);
console.log(numeroA <= numeroB);